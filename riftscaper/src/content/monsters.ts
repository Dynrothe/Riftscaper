// What lives in the rifts: monsters and the bosses at the end of each, as plain data with the
// cache's own ids. NPC ids with their idle, walk, attack and death animations, and their sounds,
// are the ones Sellswords checked against this cache (sellswords/src/content/units.ts). Life and
// damage are at level 1; the rift's level scales them (rules.ts). Tuned with the balance bot (scripts/balance.ts).
import { SPOT, Visual } from "./visuals";

export type Seqs = { idle: number; walk: number; attack: number; death: number };
export type Sounds = { attack: number; hit: number; death: number };

export type MonsterDef = {
    id: string;
    name: string;
    npcId: number;
    seqs: Seqs;
    sounds: Sounds;
    // At level 1
    life: number;
    damage: [number, number];
    armour: number;
    // Seconds between attacks, and how far into one its hit lands
    attackSeconds: number;
    hitAt: number;
    // Tiles a second
    speed: number;
    // Tiles: its body, and how far it reaches with a blow
    radius: number;
    reach: number;
    // Shoots or casts from afar instead, keeping at least `keep` tiles away
    ranged?: { range: number; keep: number; visual: Visual; speed: number };
    xp: number;
    // Drawn bigger or smaller than its model
    scale?: number;
    // Never drawn bigger than this, in tiles from its middle
    maxRadius?: number;
    // Drawn as this bake instead of its own: a guardian's form (BossDef forms)
    look?: string;
};

// A boss's own blow, every so often besides its attacks
export type BossSpecial =
    // A slam round itself: get out of the ring before it lands
    | { kind: "slam"; radius: number; damage: number; windup: number; visual: Visual }
    // Projectiles in every direction
    | { kind: "nova"; count: number; damage: number; visual: Visual; speed: number }
    // Things falling on where you stand, a moment after it marks them
    | { kind: "rain"; count: number; radius: number; damage: number; windup: number; visual: Visual }
    // A line marked on the ground to the hero, which it then runs, striking all along it
    | { kind: "charge"; length: number; width: number; damage: number; windup: number; visual: Visual }
    // A pack of its rift's own called up round it
    | { kind: "summon"; count: number; damage: number; visual: Visual }
    // Ground round the hero that burns or freezes a while: get off it
    | { kind: "field"; radius: number; seconds: number; damage: number; ailment: "burn" | "chill"; visual: Visual };

export type BossDef = MonsterDef & {
    title: string;
    special: BossSpecial;
    specialSeconds: number;
    // More specials, used in turn after the first (the Heart's guardian has every kind)
    more?: BossSpecial[];
    // A guardian that stays where it rises and changes form as it fights (docs/late-game.md,
    // phase 6: the Kraken, Zulrah): its forms in turn, so long each, each drawn as its own bake
    // and fighting as it says; what it's drawn as till it wakes (the Kraken's whirlpool); and the
    // spot as it changes
    forms?: BossForm[];
    formSeconds?: number;
    asleep?: BossForm;
    formSpot?: number;
};

// One of a guardian's forms: what it's drawn as (its own bake, named `look`), how it strikes, and
// its special, if not the guardian's
export type BossForm = {
    look: string;
    npcId: number;
    seqs: Seqs;
    ranged?: MonsterDef["ranged"];
    reach?: number;
    hitAt?: number;
    special?: BossSpecial;
};

// A guardian as one of its forms: the same guardian (its id, its life, its name), drawn and
// fighting as the form
export function formDef(boss: BossDef, form: BossForm): BossDef {
    return { ...boss, look: form.look, npcId: form.npcId, seqs: form.seqs, ranged: form.ranged, reach: form.reach ?? boss.reach, hitAt: form.hitAt ?? boss.hitAt, special: form.special ?? boss.special };
}

// A guardian's forms as monsters to bake, each under its look
export function bossLooks(boss: BossDef): MonsterDef[] {
    return [...(boss.asleep ? [boss.asleep] : []), ...(boss.forms ?? [])].map((form) => ({ ...formDef(boss, form), id: form.look, look: undefined }));
}

// Every special a guardian has, its forms' too (for the assets)
export function allBossSpecials(boss: BossDef): BossSpecial[] {
    return [...bossSpecials(boss), ...(boss.forms ?? []).flatMap((f) => (f.special ? [f.special] : []))];
}

// A guardian's specials, in the order it uses them
export function bossSpecials(boss: BossDef): BossSpecial[] {
    return [boss.special, ...(boss.more ?? [])];
}

